def li(g_, h3, sum_, desc, take, q, since, traffic, tags, rank=None, term=None, plat=None, link=None, img=None, credit=None, need=None, shop=None):
    tg = ''.join('<span class="tag">%s</span>' % t for t in tags)
    ex = ''
    for k, v in (('term', term), ('plat', plat), ('link', link), ('img', img), ('credit', credit), ('need', need), ('shop', shop)):
        if v:
            ex += ' data-%s="%s"' % (k, v)
    r = '          <span class="rank">%s</span>\n' % rank if rank else ''
    return ('        <li class="item" data-group="%s" data-sum="%s" data-take="%s"'
            ' data-q="%s" data-since="%s" data-traffic="%s"%s>\n%s'
            '          <h3>%s</h3>\n          <p>%s</p>\n'
            '          <div class="meta">%s</div>\n        </li>'
            % (g_, sum_, take, q, since, traffic, ex, r, h3, desc, tg))


def sec(cat, plat, title, en, items, src):
    return ('    <section class="cat" data-cat="%s" data-plat="%s">\n'
            '      <div class="cat-head"><h2>%s</h2><span class="en">%s</span></div>\n'
            '      <ul class="items">\n%s\n      </ul>\n'
            '      <p class="src">출처 · %s</p>\n    </section>' % (cat, plat, title, en, '\n'.join(items), src))


