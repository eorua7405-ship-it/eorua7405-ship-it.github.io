import io, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
g = io.open(os.path.join(HERE, 'board.html'), encoding='utf-8').read()

WEEK = re.search(r'<b>WEEK (\d+)</b>', g).group(1)
